<?php

namespace App\Support;

/**
 * مولّد باركود Code 128B كـSVG — من غير أي مكتبة خارجية.
 *
 * بيتستخدم في فاتورة أوردر الأونلاين: النص "pro1234"، المسدس بيقراه
 * ويكتبه حرفياً في خانة البحث فبيترجم لرقم الأوردر.
 *
 * Code 128: كل رمز 11 وحدة عرض (٣ خطوط و٣ فراغات)، ورمز الوقف 13.
 * الجدول تحت هو أنماط العرض القياسية (bar,space,bar,space,bar,space)
 * للرموز 0-106. الـchecksum = (start + Σ قيمة×موضع) mod 103.
 */
class Code128
{
    /** أنماط العرض القياسية لرموز Code 128 (كل صف 6 أرقام مجموعهم 11) */
    private const PATTERNS = [
        '212222', '222122', '222221', '121223', '121322', '131222', '122213',
        '122312', '132212', '221213', '221312', '231212', '112232', '122132',
        '122231', '113222', '123122', '123221', '223211', '221132', '221231',
        '213212', '223112', '312131', '311222', '321122', '321221', '312212',
        '322112', '322211', '212123', '212321', '232121', '111323', '131123',
        '131321', '112313', '132113', '132311', '211313', '231113', '231311',
        '112133', '112331', '132131', '113123', '113321', '133121', '313121',
        '211331', '231131', '213113', '213311', '213131', '311123', '311321',
        '331121', '312113', '312311', '332111', '314111', '221411', '431111',
        '111224', '111422', '121124', '121421', '141122', '141221', '112214',
        '112412', '122114', '122411', '142112', '142211', '241211', '221114',
        '413111', '241112', '134111', '111242', '121142', '121241', '114212',
        '124112', '124211', '411212', '421112', '421211', '212141', '214121',
        '412121', '111143', '111341', '131141', '114113', '114311', '411113',
        '411311', '113141', '114131', '311141', '411131', '211412', '211214',
        '211232', '2331112',
    ];

    private const START_B = 104;

    private const STOP = 106;

    /**
     * SVG جاهز للحقن في الصفحة — عرض تلقائي حسب طول النص.
     *
     * @param  string  $text  ASCII بس (أرقام وحروف لاتيني) — Code 128B
     */
    public static function svg(string $text, int $height = 60, int $module = 2): string
    {
        // Code 128B بيغطي ASCII 32-127 — أي حاجة بره بتتشال
        $text = preg_replace('/[^\x20-\x7E]/', '', $text) ?? '';

        if ($text === '') {
            return '';
        }

        $codes = [self::START_B];
        $sum = self::START_B;

        foreach (str_split($text) as $i => $ch) {
            $v = ord($ch) - 32;
            $codes[] = $v;
            $sum += $v * ($i + 1);
        }

        $codes[] = $sum % 103;   // checksum
        $codes[] = self::STOP;

        // بنبني المستطيلات: النمط بيتقري bar,space,bar,space...
        $x = 10 * $module;       // quiet zone
        $rects = '';

        foreach ($codes as $code) {
            $pattern = self::PATTERNS[$code];

            foreach (str_split($pattern) as $idx => $w) {
                $wpx = ((int) $w) * $module;

                if ($idx % 2 === 0) {   // خط أسود
                    $rects .= '<rect x="'.$x.'" y="0" width="'.$wpx
                        .'" height="'.$height.'" fill="#000"/>';
                }

                $x += $wpx;
            }
        }

        $width = $x + 10 * $module;   // quiet zone تانية

        return '<svg xmlns="http://www.w3.org/2000/svg" width="'.$width
            .'" height="'.$height.'" viewBox="0 0 '.$width.' '.$height
            .'" shape-rendering="crispEdges">'
            .'<rect width="'.$width.'" height="'.$height.'" fill="#fff"/>'
            .$rects
            .'</svg>';
    }
}
