<?php

namespace App\Models\Concerns;

/**
 * ═══════════════════════════════════════════════════════════════
 * ترقيم المستندات — **بأكبر رقم مش بآخر صف**  ·  ١٥ أغسطس ٢٠٢٦
 * ═══════════════════════════════════════════════════════════════
 *
 * ═══ الباج اللي الترايت ده بيصلحه ═══
 *
 * كل موديل بيرقّم مستندات (١٥ موديل) كان بيعمل:
 *
 *     $last = static::query()->orderByDesc('id')->value('number');
 *     $n = $last ? ((int) preg_replace('/\D+/', '', $last)) + 1 : $start;
 *
 * يعني بياخد رقم **آخر صف اتكتب** (بالـid) ويزوّد واحد. وده بيفترض
 * إن أعلى id معاه دايماً أعلى رقم — افتراض بيقع في تلات حالات:
 *
 *   ١. **إدخال بتاريخ قديم** — اتكشف فعلياً: استوردنا PCK-1021
 *      فبقى أعلى id، فـ`nextNumber` طلعت 1022 — ورقم PCK-1022
 *      كان موجود من قبل لإذن أقدم. النتيجة:
 *      `Duplicate entry 'PCK-1022' for key 'number_unique'`.
 *   ٢. **مسح أعلى مستند** ثم إنشاء واحد جديد → بيعيد استخدام رقم
 *      اتشال، والمراجع القديمة تبقى بتشاور على مستند تاني.
 *   ٣. **أي ترتيب غير متسلسل** (استيراد، سيدر، دمج داتا).
 *
 * الصح إن الرقم الجديد = **أكبر رقم موجود + ١**، بغض النظر عن
 * ترتيب الإدخال.
 *
 * ⚠️ `SUBSTRING_INDEX(number,'-',-1)` بتاخد اللي بعد آخر شرطة —
 * بتشتغل مع `INV-1001` و`SPAY-1001` و`PO-2001` بنفس الكفاءة.
 * و`CAST(... AS UNSIGNED)` بيتجاهل أي حروف زايدة.
 *
 * ⚠️ **مش قفل على التزامن.** ريكوستين في نفس اللحظة ممكن ياخدوا
 * نفس الرقم — بس الـunique index على العمود هو خط الدفاع، وهو
 * موجود. الفرق إن الصدام بقى نادر (سباق حقيقي) بدل ما كان حتمي
 * (أي إدخال غير متسلسل).
 */
trait HasDocumentNumber
{
    /**
     * الرقم التالي في السلسلة.
     *
     * @param  string  $prefix  البادئة بشرطتها — 'INV-'
     * @param  int  $start  أول رقم لو الجدول فاضي
     */
    protected static function nextDocumentNumber(string $prefix, int $start): string
    {
        $max = (int) static::query()
            ->selectRaw("MAX(CAST(SUBSTRING_INDEX(number, '-', -1) AS UNSIGNED)) as n")
            ->value('n');

        return $prefix.($max > 0 ? $max + 1 : $start);
    }
}
