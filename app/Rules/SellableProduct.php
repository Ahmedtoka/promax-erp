<?php

namespace App\Rules;

use App\Models\Product;
use Closure;
use Illuminate\Contracts\Validation\ValidationRule;

/**
 * ═══════════════════════════════════════════════════════════════
 * الصنف ده ينفع يتباع؟  ·  ١٧ أغسطس ٢٠٢٦
 * ═══════════════════════════════════════════════════════════════
 *
 * بديل `exists:products,id` في **كل مسار كتابة** بياخد `product_id`.
 *
 * ═══ ليه دي الحدود الحقيقية مش فلترة المنتقي ═══
 *
 * ⚠️⚠️ أودِت ١٧/٨ لقى **٩ إندبوينتس** بتقبل أي `product_id` موجود في
 * الجدول: الفواتير، المرتجعات، الهدايا، طلبات البضاعة، تسليم أوامر
 * التوريد، استلام المخزن، التحويلات، وريفيل البروموتر. كلها كانت
 * `exists:products,id` وبس.
 *
 * فلترة المنتقي **شكل**: بتخفي الصنف من الليستة، وأي طلب متأخر أو
 * أبلكيشن بنسخة قديمة أو ريكوست متكرر بيعدّي. الفاليديشن هو اللي
 * بيمنع فعلاً.
 *
 * ⚠️ **الرسالة بتقول اسم الصنف مش رقمه.** المندوب اللي بيتقفل في
 * وشه لازم يعرف أنهي صنف عشان يشيله من الطلب — `المنتج 47 غير مفعّل`
 * مايساعدوش في حاجة.
 *
 * ⚠️ **بتفحص الوجود كمان.** لو استخدمناها جنب `exists` كانت هتدي
 * رسالتين لنفس المشكلة؛ وهي لوحدها بتغطي الاتنين.
 *
 * الاستخدام:
 *   'items.*.product_id' => ['required', new SellableProduct],
 */
class SellableProduct implements ValidationRule
{
    public function validate(string $attribute, mixed $value, Closure $fail): void
    {
        $product = Product::find($value);

        // ⚠️ **الرسالة مترجمة هنا من غير `->translate()`.** الميثود دي
        // بتترجم **مفتاح** بيتبعت خام؛ ومع نص مترجم أصلاً بتدوّر على
        // مفتاح بالجملة العربية كلها وترجّعها زي ما هي — يعني بتشتغل
        // بالصدفة وبتقع أول ما نضيف متغير.
        if ($product === null) {
            $fail(__('api.product_missing'));

            return;
        }

        if (! $product->isSellable()) {
            $fail(__('api.product_draft', [
                'product' => $product->displayName(),
            ]));
        }
    }
}
