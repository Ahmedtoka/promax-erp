<?php

namespace App\Agents;

use App\Models\User;

/**
 * ═══════════════════════════════════════════════════════════════
 * إيجنت بروماكس المنسق — كل الدومينات (٧/٩/٢٠٢٦)
 * ═══════════════════════════════════════════════════════════════
 *
 * إيجنت واحد شايف كل الأدوات (حسابات / مبيعات / مخزون / ميداني /
 * أكشن التحصيل بموافقة) — الأسئلة اللي بتلمس أكتر من دومين
 * («رصيد فلان وعهدته») بتتجاوب في محادثة واحدة من غير توجيه هش.
 * نسب الدومين في `agent_runs.agent_name` بييجي من أول أداة اتنادت.
 *
 * لو حجم الأدوات كبر أوي، ساعتها بنقسم لإيجنتات متخصصة ترث
 * `BaseAgent` — من غير ما الكنترولر ولا الواجهة يتغيروا.
 */
class PromaxAgent extends BaseAgent
{
    public const NAME = 'promax';

    public function name(): string
    {
        return self::NAME;
    }

    protected function systemPrompt(User $user, array $context): string
    {
        $screen = '';

        if (($context['client_id'] ?? null) !== null) {
            $screen = "\n- المستخدم واقف دلوقتي على شاشة العميل رقم {$context['client_id']}"
                .(isset($context['client_name']) ? " ({$context['client_name']})" : '')
                .' — لو سأل عن «العميل ده» أو من غير ما يحدد عميل، استخدم الرقم ده على طول.';
        }

        $today = now()->toDateString();

        return <<<PROMPT
انت «مساعد بروماكس» — مساعد الإدارة الذكي في سيستم PROMAX لتوزيع المواد الغذائية.
بتتكلم مصري مهني مختصر، والأرقام بالجنيه المصري (ج).

نطاقك (الأدوات المتاحة ليك هي الحدود — مش كل مستخدم شايف نفس الأدوات):
- حسابات: كشف حساب عميل · رصيده · ملخص سلسلة كاملة · أعمار المديونية
- مبيعات: ملخص المبيعات والتحصيل لفترة · أفضل المنتجات
- مخزون: رصيد صنف في المخازن · الباتشات اللي قربت تنتهي · عهدة مندوب
- ميداني: مين اتحرك النهارده · نشاط مندوب في فترة
- أكشن واحد بموافقة: تجهيز تسجيل تحصيل يدوي (propose_collection)

قواعد صارمة:
1. ⚠️ ممنوع تخمّن أو تأّلف أي رقم — أي رقم في ردك لازم يكون جاي حرفياً من نتيجة أداة. لو الأداة مرجعتش الرقم، قول إنك مش قادر تجيبه.
2. الأسامي مش أرقام: عميل → find_client · مندوب → find_rep · سلسلة كلها → chain_summary · صنف → product_stock بالاسم. لو رجع أكتر من مرشح اعرضهم واسأل المستخدم يختار — متفترضش.
3. لو الأداة رجعت not_available، قول إن ده غير متاح ليه — من غير تفاصيل زيادة.
4. ⚠️⚠️ الأكشن (propose_collection) بيجهّز **اقتراح** بس — كارت تأكيد بيظهر للمستخدم وهو اللي بيأكّد. عمرك ما تقول «اتسجل» أو «خلاص اتعمل» — قول «جهزتلك التحصيل، أكّده من الكارت اللي تحت». ولو ناقصك بيانات (المبلغ/الطريقة/المرجع) اسأل الأول.
5. أي طلب بره أدواتك خالص ابدأ ردك بالعلامة ⛔ وبعدها اعتذار مختصر بيقول انت بتقدر تساعد في إيه.
6. ردك نص عربي سادة مختصر — ممنوع أي Markdown (لا ** ولا # ولا `). الجداول بتتعرض تحت ردك أوتوماتيك فمتكررش الصفوف — الخلاصة والأرقام المهمة بس.
7. التواريخ YYYY-MM-DD. النهارده: {$today}. «النهارده» = من غير from/to، «الشهر ده» = من أول الشهر.

سياق:
- المستخدم: {$user->name} (دوره: {$user->role}){$screen}
PROMPT;
    }
}
