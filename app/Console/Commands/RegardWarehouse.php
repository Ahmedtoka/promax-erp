    public function handle(): int
    {
        if (Setting::read(self::FLAG)) {
            $this->error('❌ الجرد ده اتنفذ قبل كده ('.self::FLAG.' = '.Setting::read(self::FLAG).') — ممنوع يتكرر.');

            return self::FAILURE;
        }

        // ═══ المخزن ═══
        $wh = $this->option('warehouse')
            ? Warehouse::find((int) $this->option('warehouse'))
            : Warehouse::where('name', 'like', '%معادي%')->first();

        if ($wh === null) {
            $this->error('❌ ملقتش المخزن — حدده بـ --warehouse=ID');

            return self::FAILURE;
        }

        $this->info("🏭 المخزن: {$wh->displayName()} (#{$wh->id})");

        // ═══ فحص الصفوف قبل أي حاجة (المعاينة والتنفيذ نفس الفحص) ═══
        $products = Product::whereIn('barcode', array_unique(array_column(self::ROWS, 0)))
            ->get()->keyBy('barcode');

        $plan = [];       // [باركود، باتش، تاريخ، قطع، [رف => كمية]]
        $problems = [];
        $totals = [];     // باركود => قطع

        foreach (self::ROWS as $i => [$bc, $batchNo, $date, $cart, $box, $pcs, $locs]) {
            $p = $products->get($bc);

            if ($p === null) {
                $problems[] = "صف #{$i}: مفيش صنف بباركود {$bc} (باتش {$batchNo})";

                continue;
            }

            $pieces = $pcs;

            if ($cart > 0) {
                $per = (int) $p->units_per_case;
                if ($per <= 0) {
                    $problems[] = "«{$p->name}»: الصف فيه كراتين والصنف ملوش units_per_case — ظبط وحداته الأول";

                    continue;
                }
                $pieces += $cart * $per;
            }

            if ($box > 0) {
                $per = (int) $p->box_units;
                if ($per <= 0) {
                    $problems[] = "«{$p->name}»: الصف فيه علب والصنف ملوش box_units — ظبط وحداته الأول (باتش {$batchNo})";

                    continue;
                }
                $pieces += $box * $per;
            }

            if ($pieces <= 0) {
                continue;
            }

            // توزيع القطع على الأرفف بالتساوي — الباقي لأول رف
            $codes = explode('+', $locs);
            $n = count($codes);
            $each = intdiv($pieces, $n);
            $split = [];
            foreach ($codes as $j => $code) {
                $split[$code] = $each + ($j === 0 ? $pieces - $each * $n : 0);
            }

            $plan[] = [$p, $batchNo, $date, $pieces, $split];
            $totals[$bc] = ($totals[$bc] ?? 0) + $pieces;
        }

        // ═══ المعاينة ═══
        $this->line('');
        $this->info('📋 الخطة: '.count($plan).' باتش على أرفف A01..J05');
        $this->table(['الصنف', 'القطع'], collect($totals)->map(
            fn ($q, $bc) => [$products[$bc]->name, number_format($q)]
        )->values()->all());

        $oldQty = (int) Batch::where('warehouse_id', $wh->id)->sum('qty_remaining');
        $this->line("🗑 هيتصفّر من المخزن حالياً: ".number_format($oldQty).' قطعة');

        if ($problems !== []) {
            $this->line('');
            $this->error('⚠️ مشاكل لازم تتحل قبل التنفيذ:');
            foreach ($problems as $pr) {
                $this->line('   • '.$pr);
            }
        }

        if (! $this->option('apply')) {
            $this->line('');
            $this->comment('👁 معاينة بس — مفيش حاجة اتكتبت. التنفيذ: php artisan promax:regard --apply');

            return $problems === [] ? self::SUCCESS : self::FAILURE;
        }

        if ($problems !== []) {
            $this->error('❌ مفيش تنفيذ والمشاكل دي موجودة.');

            return self::FAILURE;
        }

        // ═══ التنفيذ — ترانزاكشن واحدة ═══
        DB::transaction(function () use ($wh, $plan) {
            // ١. الأرفف الجديدة A01..J05
            foreach (self::STANDS as $stand) {
                for ($lvl = 1; $lvl <= self::LEVELS; $lvl++) {
                    Location::firstOrCreate(
                        ['warehouse_id' => $wh->id, 'code' => $stand.'0'.$lvl],
                        ['stand' => $stand, 'level' => $lvl, 'is_pick_face' => true, 'active' => true],
                    );
                }
            }

            // ٢. التصفير الكامل — الفرق بيتسجل qty_damaged (قاعدة عجز الجرد)
            $locationIds = Location::where('warehouse_id', $wh->id)->pluck('id');
            BatchLocation::whereIn('location_id', $locationIds)->update(['qty' => 0]);

            Batch::where('warehouse_id', $wh->id)
                ->where('qty_remaining', '>', 0)
                ->orderBy('id')->lockForUpdate()->get()
                ->each(function (Batch $b) {
                    $b->update([
                        'qty_damaged' => (int) $b->qty_damaged + (int) $b->qty_remaining,
                        'qty_remaining' => 0,
                    ]);
                });

            // ٣. باتشات الجرد الجديدة على أرففها
            foreach ($plan as [$product, $batchNo, $date, $pieces, $split]) {
                $batch = Batch::firstOrNew([
                    'warehouse_id' => $wh->id,
                    'product_id' => $product->id,
                    'batch_no' => $batchNo,
                ]);

                $batch->fill([
                    'produced_on' => $date,
                    'expires_on' => $product->expiryFrom($date),
                    'qty_received' => (int) $batch->qty_received + $pieces,
                    'qty_remaining' => (int) $batch->qty_remaining + $pieces,
                    'cost' => (float) ($batch->cost ?: $product->cost),
                ])->save();

                foreach ($split as $code => $qty) {
                    $loc = Location::where('warehouse_id', $wh->id)->where('code', $code)->first();

                    if ($loc === null) {
                        throw new \RuntimeException("رف {$code} مش موجود");
                    }

                    if ($err = BatchLocation::putAway($batch, $loc, $qty)) {
                        throw new \RuntimeException("ترصيف {$batchNo} على {$code}: {$err}");
                    }
                }
            }

            // ٤. مزامنة stocks للتلات مستويات — لكل الأصناف اللي اتلمست
            $touched = Batch::where('warehouse_id', $wh->id)->distinct()->pluck('product_id');
            foreach ($touched as $pid) {
                StockCounting::resync((int) $pid);
            }

            Setting::write(self::FLAG, now()->toDateTimeString());
        });

        $this->info('✅ اتنفذ: المخزن اتصفّر، والجرد الجديد اترصّف على استانداته. افتح /wh/shelves تتأكد.');

        return self::SUCCESS;
    }
