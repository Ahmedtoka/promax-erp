    public function handle(): int
    {
        $clients = Client::where('status', 'active')->orderBy('code')->get();

        // «مافيهوش حرف عربي واحد» = الخانة العربي فيها إنجليزي
        $latin = $clients->filter(fn ($c) => ! preg_match('/\p{Arabic}/u', (string) $c->name));

        if ($latin->isEmpty()) {
            $this->info('✅ كل العملاء النشطين ليهم أسماء عربي.');

            return self::SUCCESS;
        }

        if ($this->option('fix')) {
            $n = 0;

            foreach ($latin as $c) {
                $ar = self::NAMES[$c->code] ?? null;

                if ($ar === null) {
                    continue;
                }

                // ⚠️ الإنجليزي الحالي بيتحفظ في name_en لو كانت فاضية —
                // قبل ما العربي ياخد مكانه في name
                $c->update([
                    'name' => $ar,
                    'name_en' => $c->name_en ?: $c->name,
                ]);
                $n++;
            }

            $this->info("✓ اتكتب الاسم العربي لـ $n عميل من القاموس.");

            $left = $latin->count() - $n;

            if ($left > 0) {
                $this->warn("فاضل $left عميل مش في القاموس — شغّل promax:names من غير --fix وابعت القايمة عشان نكمّل القاموس، أو اكتبهم من كروت العملاء.");
            }

            return self::SUCCESS;
        }

        $this->warn("⚠️ {$latin->count()} عميل من {$clients->count()} «اسمهم العربي» مكتوب إنجليزي:");
        $this->newLine();

        // كلهم — القايمة دي بتتبعت عشان يتكمّل بيها القاموس
        $this->table(
            ['الكود', 'الاسم الحالي (في خانة العربي)', 'الإنجليزي'],
            $latin->map(fn ($c) => [
                $c->code,
                mb_substr((string) $c->name, 0, 40),
                mb_substr((string) $c->name_en, 0, 40),
            ])->all(),
        );

        $this->newLine();
        $this->line('التصليح: افتح كارت العميل في الـERP واكتب الاسم في خانة «الاسم بالعربي» —');
        $this->line('هيظهر فوراً في الأبلكيشن وكل الشاشات العربي.');

        return self::SUCCESS;
    }
